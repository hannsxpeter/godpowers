'use strict';
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const project = __dirname;
const source = '/Users/hannsxpeter/Projects/godpowers';
const meta = JSON.parse(fs.readFileSync(path.join(project,'metadata.json'),'utf8'));
const files = ['lib/command-families.js','lib/invocation-policy.js','SKILL.md','skills/god.md','skills/god-mode.md','skills/god-debug.md','specialists/god-debugger.md','routing/god-debug.yaml','references/orchestration/GOD-ORCHESTRATOR-RUNBOOK.md'];
meta.lastBehaviorChangeAt = new Date(Math.max(...files.map(f => fs.statSync(path.join(source,f)).mtimeMs))).toISOString();
meta.claim = 'Adaptive routing retains recommendation-only authority and refuses the fast path for every ineligible mutation across source, npm, installed Codex, and serialized consumer boundaries.';
meta.command = 'node ' + path.join(project,'probe.js');
fs.writeFileSync(path.join(project,'metadata.json'),JSON.stringify(meta,null,2)+'\n');
if (!fs.existsSync(path.join(project,'.godpowers/state.json'))) require(path.join(source,'lib/state')).init(project,'stage2-authority-review');
const args = ['--offline','--no-install','godpowers','verify',meta.command,'--substep='+meta.substep,'--claim='+meta.claim,'--project='+project,'--timeout=60','--json'];
const result = cp.spawnSync('npx',args,{cwd:project,encoding:'utf8',timeout:70000,maxBuffer:1024*1024,env:{...process.env,npm_config_offline:'true'}});
fs.writeFileSync(path.join(project,'verify-private.json'),result.stdout || result.stderr || '');
if(result.error) throw result.error;
const raw = JSON.parse(result.stdout);
const resolved = require(path.join(source,'lib/evidence')).resolveReviewEvidence(raw.record.id,{projectRoot:project,expectedClaim:meta.claim,expectedCommand:meta.command,expectedSubstep:meta.substep,reviewWindowStartedAt:meta.reviewWindowStartedAt,lastBehaviorChangeAt:meta.lastBehaviorChangeAt});
fs.writeFileSync(path.join(project,'review-projection.json'),JSON.stringify(resolved,null,2)+'\n');
console.log(JSON.stringify(resolved,null,2));
if (result.status !== 0 || !resolved.accepted) { console.log('Probe failure diagnostics: '+String(raw.diagnostics || '').slice(0,2000)); process.exitCode=1; }
